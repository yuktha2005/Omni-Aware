import os
import uuid
import smtplib
import logging
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from datetime import datetime, timezone
from typing import Any, Tuple, Optional
from services.distribution.channels.base import BaseChannelProvider, ChannelSendResult

logger = logging.getLogger(__name__)


class EmailChannelProvider(BaseChannelProvider):
    channel_name: str = "email"

    def __init__(self):
        self.smtp_host = os.getenv("SMTP_HOST", "")
        self.smtp_port = int(os.getenv("SMTP_PORT", "587"))
        self.smtp_user = os.getenv("SMTP_USER", "")
        self.smtp_password = os.getenv("SMTP_PASSWORD", "")
        self.from_email = os.getenv("SMTP_FROM_EMAIL", "noreply@publicawareness.gov.in")
        self.use_tls = os.getenv("SMTP_USE_TLS", "true").lower() in ["true", "1", "yes"]
        self.force_mock = os.getenv("EMAIL_FORCE_MOCK", "true").lower() in ["true", "1", "yes"]

        self.is_mock = self.force_mock or not bool(self.smtp_host and self.smtp_user)
        self.provider_name = "Mock-SMTP-Provider" if self.is_mock else f"SMTP-{self.smtp_host}"

    def check_eligibility(self, recipient: Any) -> Tuple[bool, str, Optional[str]]:
        if not recipient:
            return False, "Recipient record is missing", None
        
        # Check active status
        if getattr(recipient, "status", "active") != "active":
            return False, f"Recipient is {getattr(recipient, 'status', 'inactive')}", None

        # Check consent
        consent = getattr(recipient, "consent_status", "consented")
        if consent in ["opted_out", "unsubscribed", "revoked"]:
            return False, f"Recipient consent status is {consent}", None

        email = getattr(recipient, "email", None)
        if not email or "@" not in email or "." not in email:
            return False, "Recipient has invalid or missing email address", None

        return True, "Eligible for email delivery", email

    def send(
        self,
        recipient: Any,
        content: Any,
        campaign: Any,
        **kwargs
    ) -> ChannelSendResult:
        eligible, reason, email = self.check_eligibility(recipient)
        if not eligible:
            return ChannelSendResult(
                success=False,
                status="FAILED",
                message_id=f"fail-{uuid.uuid4().hex[:12]}",
                provider=self.provider_name,
                error_message=reason
            )

        subject = getattr(content, "message_title", "Public Awareness Notification")
        body_text = getattr(content, "message_body", "")
        call_to_action = getattr(content, "call_to_action", None)
        cta_html = f"<p><strong>Action:</strong> <a href='#'>{call_to_action}</a></p>" if call_to_action else ""

        html_content = f"""
        <div style="font-family: Arial, sans-serif; max-width: 600px; margin: 0 auto; padding: 20px; border: 1px solid #e2e8f0; border-radius: 8px;">
            <h2 style="color: #1e3a8a;">{subject}</h2>
            <div style="color: #334155; line-height: 1.6; white-space: pre-line;">{body_text}</div>
            {cta_html}
            <hr style="border: none; border-top: 1px solid #e2e8f0; margin: 20px 0;" />
            <p style="font-size: 12px; color: #94a3b8;">
                This public awareness bulletin was generated by the Multilingual Mass Communication Platform.
            </p>
        </div>
        """

        message_id = f"email-{uuid.uuid4().hex[:16]}"
        now = datetime.now(timezone.utc)

        if self.is_mock:
            # Mock mode: simulates instantaneous delivery
            logger.info(f"[MOCK EMAIL] Delivered to {email} | MessageID: {message_id} | Subject: {subject}")
            return ChannelSendResult(
                success=True,
                status="DELIVERED",
                message_id=message_id,
                provider="Mock-SMTP-Provider (Dev Mode)",
                response_data={
                    "recipient_email": email,
                    "subject": subject,
                    "content_length": len(body_text),
                    "mock": True
                },
                sent_at=now,
                delivered_at=now
            )

        # Production SMTP send
        try:
            msg = MIMEMultipart("alternative")
            msg["Subject"] = subject
            msg["From"] = self.from_email
            msg["To"] = email
            msg["Message-ID"] = f"<{message_id}@{self.smtp_host}>"

            part1 = MIMEText(body_text, "plain", "utf-8")
            part2 = MIMEText(html_content, "html", "utf-8")
            msg.attach(part1)
            msg.attach(part2)

            with smtplib.SMTP(self.smtp_host, self.smtp_port, timeout=10) as server:
                if self.use_tls:
                    server.starttls()
                if self.smtp_user and self.smtp_password:
                    server.login(self.smtp_user, self.smtp_password)
                server.sendmail(self.from_email, [email], msg.as_string())

            return ChannelSendResult(
                success=True,
                status="SENT",
                message_id=message_id,
                provider=self.provider_name,
                response_data={"recipient_email": email, "smtp_response": "250 OK"},
                sent_at=now,
                delivered_at=now
            )
        except Exception as e:
            logger.error(f"Failed to send email to {email}: {e}")
            return ChannelSendResult(
                success=False,
                status="FAILED",
                message_id=message_id,
                provider=self.provider_name,
                error_message=str(e),
                failed_at=now
            )
